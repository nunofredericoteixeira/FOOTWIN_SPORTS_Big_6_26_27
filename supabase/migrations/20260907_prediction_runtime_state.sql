-- FOOTWIN SPORTS
-- Persistência runtime de previsões, avaliações e onzes.
--
-- A SQLite continua a ser a base operacional local.
-- Estas tabelas guardam o estado mutável criado em runtime,
-- sobrevivendo a deploys/restarts do Render.
--
-- Leitura e escrita serão efetuadas exclusivamente pelos
-- processos internos usando SUPABASE_SERVICE_ROLE_KEY.

CREATE TABLE IF NOT EXISTS public.runtime_match_predictions (
    prediction_id text PRIMARY KEY,

    match_id text NOT NULL,
    model_version text NOT NULL,
    run_id text,

    prediction_timestamp timestamptz NOT NULL,
    data_cutoff timestamptz,

    lambda_home double precision NOT NULL,
    lambda_away double precision NOT NULL,

    home_win_probability double precision NOT NULL,
    draw_probability double precision NOT NULL,
    away_win_probability double precision NOT NULL,

    most_likely_score text,
    second_likely_score text,
    third_likely_score text,

    over_2_5_probability double precision,
    btts_probability double precision,

    data_confidence double precision NOT NULL,

    created_at timestamptz NOT NULL
        DEFAULT now(),

    prediction_stage text NOT NULL
        CHECK (
            prediction_stage IN (
                'PRE_MATCH',
                'CONFIRMED_LINEUP'
            )
        ),

    prediction_version integer NOT NULL
        CHECK (
            prediction_version >= 1
        ),

    parent_prediction_id text,

    lineup_id text,
    lineup_hash text,

    lineup_confirmed boolean NOT NULL
        DEFAULT false,

    lineup_data_quality text NOT NULL
        DEFAULT 'NOT_APPLICABLE'
        CHECK (
            lineup_data_quality IN (
                'NOT_APPLICABLE',
                'COMPLETE',
                'PARTIAL_MAPPING'
            )
        ),

    is_current boolean NOT NULL
        DEFAULT true,

    input_snapshot_json text,

    superseded_at timestamptz
);

ALTER TABLE public.runtime_match_predictions
ENABLE ROW LEVEL SECURITY;

CREATE UNIQUE INDEX IF NOT EXISTS
    runtime_predictions_stage_version_unique
ON public.runtime_match_predictions (
    match_id,
    model_version,
    prediction_stage,
    prediction_version
);

CREATE UNIQUE INDEX IF NOT EXISTS
    runtime_predictions_current_stage_unique
ON public.runtime_match_predictions (
    match_id,
    model_version,
    prediction_stage
)
WHERE is_current = true;

CREATE INDEX IF NOT EXISTS
    runtime_predictions_match_idx
ON public.runtime_match_predictions (
    match_id
);

CREATE INDEX IF NOT EXISTS
    runtime_predictions_lineup_hash_idx
ON public.runtime_match_predictions (
    match_id,
    lineup_hash
);


CREATE TABLE IF NOT EXISTS public.runtime_prediction_evaluations (
    evaluation_id bigint GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    prediction_id text NOT NULL UNIQUE,

    match_id text NOT NULL,
    model_version text NOT NULL,

    prediction_stage text NOT NULL
        CHECK (
            prediction_stage IN (
                'PRE_MATCH',
                'CONFIRMED_LINEUP'
            )
        ),

    actual_home_goals integer NOT NULL
        CHECK (
            actual_home_goals >= 0
        ),

    actual_away_goals integer NOT NULL
        CHECK (
            actual_away_goals >= 0
        ),

    actual_outcome text NOT NULL
        CHECK (
            actual_outcome IN (
                '1',
                'X',
                '2'
            )
        ),

    predicted_outcome text NOT NULL
        CHECK (
            predicted_outcome IN (
                '1',
                'X',
                '2'
            )
        ),

    outcome_hit boolean NOT NULL,
    exact_score_hit boolean NOT NULL,

    brier_score double precision NOT NULL,
    log_loss double precision NOT NULL,

    evaluated_at timestamptz NOT NULL
        DEFAULT now(),

    prudent_prediction text,

    prudent_outcome_hit boolean
);

ALTER TABLE public.runtime_prediction_evaluations
ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS
    runtime_prediction_evaluations_match_idx
ON public.runtime_prediction_evaluations (
    match_id,
    evaluated_at
);

CREATE INDEX IF NOT EXISTS
    runtime_prediction_evaluations_model_idx
ON public.runtime_prediction_evaluations (
    model_version,
    prediction_stage,
    evaluated_at
);


CREATE TABLE IF NOT EXISTS public.runtime_match_lineups (
    lineup_id text PRIMARY KEY,

    match_id text NOT NULL,
    provider text NOT NULL,
    provider_fixture_id text,

    lineup_status text NOT NULL,

    home_formation text,
    away_formation text,

    lineup_hash text NOT NULL,

    announced_at timestamptz,
    fetched_at timestamptz NOT NULL,

    is_current boolean NOT NULL
        DEFAULT true,

    raw_payload_json text,

    created_at timestamptz NOT NULL
        DEFAULT now(),

    updated_at timestamptz NOT NULL
        DEFAULT now(),

    UNIQUE (
        match_id,
        lineup_hash
    )
);

ALTER TABLE public.runtime_match_lineups
ENABLE ROW LEVEL SECURITY;

CREATE UNIQUE INDEX IF NOT EXISTS
    runtime_match_lineups_current_unique
ON public.runtime_match_lineups (
    match_id
)
WHERE is_current = true;

CREATE INDEX IF NOT EXISTS
    runtime_match_lineups_match_idx
ON public.runtime_match_lineups (
    match_id,
    is_current
);

CREATE INDEX IF NOT EXISTS
    runtime_match_lineups_hash_idx
ON public.runtime_match_lineups (
    lineup_hash
);


CREATE TABLE IF NOT EXISTS public.runtime_match_lineup_players (
    lineup_player_id text PRIMARY KEY,

    lineup_id text NOT NULL,
    match_id text NOT NULL,
    team_id text NOT NULL,

    player_id text,
    provider_player_id text,

    player_name text NOT NULL,

    role text NOT NULL,

    position_code text,
    formation_position text,

    shirt_number integer,

    captain boolean NOT NULL
        DEFAULT false,

    mapping_status text NOT NULL,

    created_at timestamptz NOT NULL
        DEFAULT now(),

    UNIQUE (
        lineup_id,
        team_id,
        role,
        provider_player_id
    )
);

ALTER TABLE public.runtime_match_lineup_players
ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS
    runtime_lineup_players_lineup_idx
ON public.runtime_match_lineup_players (
    lineup_id,
    team_id,
    role
);

CREATE INDEX IF NOT EXISTS
    runtime_lineup_players_player_idx
ON public.runtime_match_lineup_players (
    player_id
);
